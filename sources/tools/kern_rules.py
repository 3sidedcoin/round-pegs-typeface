"""Rule-based pair kerning for Round Pegs capitals, in whole cells (128 units).

Usage: python3 -I kern_rules.py RoundPegs-Regular.otf kern.fea

For each rule, the closest row between the two letters is set to a target gap (in cells):
  * 0 cells (letters touch): LV LT LY
  * S before T moves in 1 cell (the S top row and lower bulge both stop short of its outer edge, so every row is 2 cells from T; tucked, every row is 1)
  * Y and V before a period or comma move in 2 cells (only the 1-cell stem is left at the baseline, so the mark tucks under the arm)
  * 1 cell: L+{C E J L O Q U W}, F/C/Z + any capital, E+Y, C+V, C+Y
Pairs already at the target are left alone. All other pairs are unkerned.
Accented capitals share their base letter's class; lowercase maps to the same glyphs.
"""
import sys, string
from fontTools.ttLib import TTFont
sys.path.insert(0, __import__('os').path.dirname(__import__('os').path.abspath(__file__)))
import kern as K

TOUCH = ['LV', 'LT', 'LY']
UNDER = []   # no pairs currently slide under a neighbour (LY used to, at -1 cell; it now touches like LV and LT)
PUNCT = [(l, g) for l in 'YV' for g in ('period', 'comma')]   # fixed -2 cells
ROWWISE = [('S', 'T')]   # fixed -1 cell: the outer-edge gap is already 1 but every row is 2 cells away
ONE = [('L', r) for r in 'CEJLOQUW'] + [(l, r) for l in 'FCZ' for r in string.ascii_uppercase] + [('E', 'Y'), ('C', 'V'), ('C', 'Y')]

def main(otf, out):
    font = TTFont(otf); hm = font['hmtx']; cm = font.getBestCmap()
    L = string.ascii_uppercase
    adv = {c: hm[cm[ord(c)]][0] / 128 for c in L}
    P = {c: K.profile(otf, c) for c in L}
    def mingap(a, b):
        # gap between the two letters' ink edges, in cells (outer edges, whatever the row)
        ra = max(r[1] for r in P[a] if r); lb = min(r[0] for r in P[b] if r)
        return (adv[a] - ra) + lb
    targets = {a + b: 1 for a, b in ONE}
    targets.update({p: 0 for p in TOUCH})
    targets.update({p: -1 for p in UNDER})
    pairs = []
    for p, t in sorted(targets.items()):
        g = mingap(*p)
        if g is None: continue
        k = round(t - g)
        if k != 0: pairs.append((p, k, g, t))
    cls = open(__import__('os').path.join(__import__('os').path.dirname(__import__('os').path.abspath(__file__)), 'kern.experimental.fea')).read().split('feature kern')[0]
    fea = '# Generated by sources/tools/kern_rules.py - whole-cell pair kerning (see documentation/DESIGN.md)\n\n' + cls.split('\n', 2)[2] + 'feature kern {\n'
    for (p, k, g, t) in pairs:
        fea += f'  pos @K_{p[0]} @K_{p[1]} {k*128};\n'
    for l, g in ROWWISE:
        fea += f'  pos @K_{l} @K_{g} -128;\n'
    for l, g in PUNCT:
        fea += f'  pos @K_{l} {g} -256;\n'
    fea += '} kern;\n'
    open(out, 'w').write(fea)
    for (p, k, g, t) in pairs: print(p, f'{g:g} -> {t}', k)
    print(len(pairs), 'pairs')

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
