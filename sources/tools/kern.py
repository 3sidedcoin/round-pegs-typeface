"""Generate class-based kerning (whole cells) from the finished font's outlines.

Usage: python3 -I kern.py RoundPegs-Regular.otf out/kern.fea [--report report.txt]

Rule: for each pair of capitals, measure per-row ink extents (5 cap rows, scanned at row centres).
Kern left, in whole cells, while (a) rows where both glyphs have ink stay >= MIN_GAP cells apart
(diagonal-adjacent rows >= MIN_DIAG), and (b) the average gap (rows without ink count as CAP) is
brought down towards TARGET. Accented capitals share their base letter's class. Lowercase maps to the
same glyphs, so it is kerned automatically.
"""
import sys, string, unicodedata
from fontTools.ttLib import TTFont
from fontTools.pens.recordingPen import DecomposingRecordingPen
from fontTools.pens.basePen import BasePen
import numpy as np
from PIL import Image, ImageDraw, ImageFont

CELL = 128
MIN_GAP, MIN_DIAG = 1.0, 0.0
TARGET, CAP = 1.75, 3.0
MAX_KERN = 2          # cells

def profile(font_path, ch, S=128):
    """per cap row (bottom to top): (left, right) ink extents in cells, or None; plus advance in cells"""
    f = ImageFont.truetype(font_path, S)
    cell = S / 8
    im = Image.new('L', (S * 2, S * 2), 0)
    ImageDraw.Draw(im).text((S // 2, int(S * 1.4)), ch, font=f, fill=255, anchor='ls')
    a = np.array(im) > 127
    base = int(S * 1.4)
    rows = []
    for r in range(5):
        y = int(base - (r + 0.5) * cell)
        xs = np.where(a[y])[0]
        rows.append((((xs.min() - S // 2) / cell), ((xs.max() + 1 - S // 2) / cell)) if len(xs) else None)
    return rows

def main(otf, out, report=None):
    font = TTFont(otf); hm = font['hmtx']; cm = font.getBestCmap()
    letters = string.ascii_uppercase
    adv = {c: hm[cm[ord(c)]][0] / CELL for c in letters}
    P = {c: profile(otf, c) for c in letters}

    def gaps(a, b, k):
        out = []
        for r in range(5):
            ra, lb = P[a][r], P[b][r]
            out.append(None if ra is None or lb is None else (adv[a] - ra[1]) + lb[0] + k)
        return out

    def avg(a, b, k):
        return np.mean([min(g, CAP) if g is not None else CAP for g in gaps(a, b, k)])

    def ok(a, b, k):
        g = gaps(a, b, k)
        if any(x is not None and x < MIN_GAP - 1e-6 for x in g): return False
        for r in range(4):                       # diagonal neighbours
            for (r1, r2) in ((r, r + 1), (r + 1, r)):
                ra, lb = P[a][r1], P[b][r2]
                if ra is not None and lb is not None and (adv[a] - ra[1]) + lb[0] + k < MIN_DIAG - 1e-6: return False
        return True

    kern = {}
    for a in letters:
        for b in letters:
            best = 0
            for k in range(-1, -MAX_KERN - 1, -1):
                if not ok(a, b, k): break
                if abs(avg(a, b, k) - TARGET) < abs(avg(a, b, best) - TARGET) - 1e-6: best = k
                else: break
            if best: kern[(a, b)] = best

    # classes: base letter + its accented capitals
    members = {c: [cm[ord(c)]] for c in letters}
    for cp, g in sorted(cm.items()):
        ch = chr(cp)
        if ch.isupper() and cp > 0x7f:
            d = unicodedata.normalize('NFD', ch)
            if d[0] in members and len(d) > 1 and g not in members[d[0]]: members[d[0]].append(g)
    lines = ['# Generated by sources/tools/kern.py - whole-cell (128 unit) pair kerning, capitals', '']
    for c in letters: lines.append('@K_%s = [%s];' % (c, ' '.join(members[c])))
    lines += ['', 'feature kern {']
    for (a, b), k in sorted(kern.items()): lines.append('  pos @K_%s @K_%s %d;' % (a, b, k * CELL))
    lines.append('} kern;')
    open(out, 'w').write('\n'.join(lines) + '\n')
    if report:
        before = [avg(a, b, 0) for a in letters for b in letters]
        after = [avg(a, b, kern.get((a, b), 0)) for a in letters for b in letters]
        with open(report, 'w') as fh:
            fh.write('pairs kerned: %d of %d\n' % (len(kern), 26 * 26))
            fh.write('avg gap before: mean %.2f  min %.2f  max %.2f  std %.2f\n' % (np.mean(before), min(before), max(before), np.std(before)))
            fh.write('avg gap after : mean %.2f  min %.2f  max %.2f  std %.2f\n' % (np.mean(after), min(after), max(after), np.std(after)))
            fh.write('by amount: ' + str({k: sum(1 for v in kern.values() if v == k) for k in sorted(set(kern.values()))}) + '\n')
            for (a, b), k in sorted(kern.items(), key=lambda x: (x[1], x[0])): fh.write('%s%s %d\n' % (a, b, k))
    return kern

if __name__ == '__main__':
    rep = sys.argv[sys.argv.index('--report') + 1] if '--report' in sys.argv else None
    main(sys.argv[1], sys.argv[2], rep)
